#!/usr/bin/env bash
# Windows bundling for the OCIO GDExtension (run inside an MSYS2 MINGW64 shell).
#
#   stage <main.dll> <out-dir> <dep-bin-dir>
#       Copy the built extension plus the full (transitive) runtime closure
#       of its DLL imports next to it. Windows has no rpath: the loader only
#       searches the directory of the executable (and PATH), so every
#       non-system DLL must ship inside the addon.
#       <dep-bin-dir> is the bin dir the extension was linked against
#       (MSYS2 /mingw64/bin); system DLLs are never bundled.
#
#   verify <main.dll> <out-dir>
#       Fail unless every import of every bundled DLL is either a Windows
#       system DLL or present in <out-dir>.
#
# Imports are read with objdump -p (PE import table); no ldd dependency.
#
# Usage: windows-bundle.sh <stage|verify> ...
set -euo pipefail

script_dir=$(cd "$(dirname "$0")" && pwd)
gdextension_template="$script_dir/../ocio.gdextension"

fail() { echo "windows-bundle: $*" >&2; exit 1; }

# DLLs that always come from Windows itself.
is_system_dll() {
	local n
	n=$(printf '%s' "$1" | tr '[:upper:]' '[:lower:]')
	case "$n" in
	kernel32.dll | kernelbase.dll | ntdll.dll | msvcrt.dll | ucrtbase.dll | \
		api-ms-win-*.dll | ext-ms-*.dll) return 0 ;;
	user32.dll | gdi32.dll | gdi32full.dll | advapi32.dll | shell32.dll | \
		shlwapi.dll | ole32.dll | oleaut32.dll | comdlg32.dll | comctl32.dll | \
		ws2_32.dll | wsock32.dll | mswsock.dll | crypt32.dll | bcrypt.dll | \
		secur32.dll | iphlpapi.dll | version.dll | psapi.dll | setupapi.dll | \
		cfgmgr32.dll | imm32.dll | winmm.dll | uxtheme.dll | dwmapi.dll | \
		rpcrt4.dll | userenv.dll | netapi32.dll | mpr.dll | dbghelp.dll | \
		d3d11.dll | d3d12.dll | dxgi.dll | opengl32.dll | glu32.dll | \
		wintrust.dll | powrprof.dll | wtsapi32.dll | msimg32.dll | \
		gdiplus.dll | dnsapi.dll | winspool.drv | winhttp.dll | wininet.dll) return 0 ;;
	esac
	return 1
}

# Imported DLL names of a PE file (lowercase, deduplicated).
imports_of() {
	objdump -p "$1" 2>/dev/null |
		awk '/DLL Name:/ { print tolower($3) }' | sort -u
}

export_path() { # Windows-style path for a POSIX path (MinGW tools accept /c/... too)
	printf '%s\n' "$1"
}

stage() { # <main.dll> <out-dir> <dep-bin-dir>
	local lib=$1 out=$2 bindir=$3 name dll src f
	[ -f "$lib" ] || fail "library not found: $lib"
	[ -d "$bindir" ] || fail "dependency bin dir not found: $bindir"
	mkdir -p "$out"
	name=$(basename "$lib")
	cp -f "$lib" "$out/$name"

	local -a queue=("$out/$name") bundled=()
	while [ ${#queue[@]} -gt 0 ]; do
		f=${queue[0]}
		queue=("${queue[@]:1}")
		while read -r dll; do
			[ -n "$dll" ] || continue
			is_system_dll "$dll" && continue
			# Imports are lowercase; the file on disk may be mixed case.
			if [ -f "$out/$dll" ]; then continue; fi
			src=$(find "$bindir" -maxdepth 1 -iname "$dll" -print -quit)
			[ -n "$src" ] || fail "cannot resolve $dll (needed by $(basename "$f"))"
			cp -L -f "$src" "$out/$(basename "$src")"
			bundled+=("$(basename "$src")")
			queue+=("$out/$(basename "$src")")
		done < <(imports_of "$f")
	done

	echo "staged $name + ${#bundled[@]} DLLs in $out"
	write_dist "$out"
}

verify() { # <main.dll> <out-dir>
	local lib=$1 out=$2 f dll bad=0 base
	[ -f "$lib" ] || fail "library not found: $lib"
	out=$(cd "$out" && pwd)
	for f in "$out"/*.dll; do
		while read -r dll; do
			[ -n "$dll" ] || continue
			is_system_dll "$dll" && continue
			if ! find "$out" -maxdepth 1 -iname "$dll" -print -quit | grep -q .; then
				echo "  $(basename "$f") imports $dll, not bundled"
				bad=$((bad + 1))
			fi
		done < <(imports_of "$f")
	done
	[ "$bad" -eq 0 ] || fail "$bad unresolved imports in $out"
	local -a arr=("$out"/*.dll)
	echo "verified: ${#arr[@]} DLLs, all imports bundled or system"
}

write_dist() { # <out-dir>
	local out=$1 dep snippet="$out/dependencies-snippet.txt"
	{
		echo "; Generated by ocio/tools/windows-bundle.sh — Windows [dependencies]"
		echo "; section for ocio.gdextension (bundled MSYS2/MinGW DLLs, copied next"
		echo "; to the exported executable)."
		printf 'windows.x86_64 = {\n'
		for dep in $(cd "$out" && ls *.dll | grep -v '^libgdocio' | sort); do
			printf '\t"res://addons/ocio/win64/%s": "",\n' "$dep"
		done
		printf '}\n'
	} > "$snippet"

	# compose-gdextension.sh turns this snippet into the descriptor (it also
	# replaces the template's static win64 list when a bundle is supplied).
	echo "wrote $snippet"
}

case "${1:-}" in
stage)
	[ $# -eq 4 ] || fail "usage: $0 stage <main.dll> <out-dir> <dep-bin-dir>"
	stage "$2" "$3" "$4"
	;;
verify)
	[ $# -eq 3 ] || fail "usage: $0 verify <main.dll> <out-dir>"
	verify "$2" "$3"
	;;
*)
	fail "usage: $0 <stage|verify> ..."
	;;
esac
